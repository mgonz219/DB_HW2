
-- Bank database schema
-- Execute in bank_db, NOT supermarket_db.

CREATE TABLE IF NOT EXISTS public.bank_account (
    account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER,
    account_type VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
    balance NUMERIC(12,2) NOT NULL DEFAULT 0.00,

    CONSTRAINT bank_balance_nonnegative
        CHECK (balance >= 0),

    CONSTRAINT bank_account_type_valid
        CHECK (
            (account_type = 'CUSTOMER' AND customer_id IS NOT NULL)
            OR
            (account_type = 'COMPANY' AND customer_id IS NULL)
        )
);

-- Index for finding accounts belonging to customers.
CREATE INDEX IF NOT EXISTS idx_bank_account_customer
ON public.bank_account (customer_id);

-- Allow only one company receiving account.
CREATE UNIQUE INDEX IF NOT EXISTS idx_single_company_account
ON public.bank_account (account_type)
WHERE account_type = 'COMPANY';

-- Records successfully committed banking transactions.
-- Used by the distributed transaction coordinator for recovery.

CREATE TABLE IF NOT EXISTS public.distributed_participant_commits (
    transaction_id UUID PRIMARY KEY,
    committed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
